from __future__ import annotations

from datetime import date, datetime
from typing import List, Optional, Protocol

from .models import (
    Candidate,
    DashboardPayload,
    ExitReplayObservation,
    PaperExitFill,
    PaperFill,
    PaperOrder,
    PaperPosition,
    ProviderReadiness,
    ReplayObservation,
    ScanRun,
    ScheduledScanJob,
    InstrumentBars,
    MarketIndex,
)


class ResearchProvider(Protocol):
    def dashboard(self) -> DashboardPayload: ...
    def candidate(self, candidate_id: str) -> Optional[Candidate]: ...


class DailyBarProvider(Protocol):
    def instruments(self) -> List[InstrumentBars]: ...
    def source(self) -> str: ...
    def market_supportive(self) -> bool: ...
    def cutoff_time(self) -> str: ...
    def readiness(self) -> ProviderReadiness: ...
    def indices(self) -> List[MarketIndex]: ...


class TradingCalendar(Protocol):
    def is_session(self, day: date) -> bool: ...
    def name(self) -> str: ...


class ReplayProvider(Protocol):
    def observation(self, symbol: str, sequence: int) -> Optional[ReplayObservation]: ...
    def count(self, symbol: str) -> int: ...


class ExitReplayProvider(Protocol):
    def observation(
        self, symbol: str, sequence: int
    ) -> Optional[ExitReplayObservation]: ...
    def count(self, symbol: str) -> int: ...


class PaperOrderRepository(Protocol):
    def initialize(self) -> None: ...
    def ping(self) -> bool: ...
    def find_by_idempotency_key(self, key: str) -> Optional[PaperOrder]: ...
    def find_by_id(self, order_id: str) -> Optional[PaperOrder]: ...
    def save(self, order: PaperOrder) -> PaperOrder: ...
    def update(self, order: PaperOrder) -> PaperOrder: ...
    def apply_fill(self, order: PaperOrder, fill: PaperFill) -> PaperOrder: ...
    def apply_replay(
        self,
        observation: ReplayObservation,
        order: Optional[PaperOrder] = None,
        fill: Optional[PaperFill] = None,
        position: Optional[PaperPosition] = None,
    ) -> None: ...
    def list_orders(self) -> List[PaperOrder]: ...
    def list_fills(self) -> List[PaperFill]: ...
    def observation_count(self, symbol: str) -> int: ...
    def record_observation(self, observation: ReplayObservation) -> None: ...
    def find_position(self, position_id: str) -> Optional[PaperPosition]: ...
    def list_positions(self) -> List[PaperPosition]: ...
    def list_exit_fills(self) -> List[PaperExitFill]: ...
    def exit_observation_count(self, symbol: str) -> int: ...
    def apply_exit_replay(
        self,
        observation: ExitReplayObservation,
        position: PaperPosition,
        fill: Optional[PaperExitFill] = None,
    ) -> None: ...


class ScanRepository(Protocol):
    def initialize(self) -> None: ...
    def ping(self) -> bool: ...
    def find_by_slot_key(self, slot_key: str) -> Optional[ScanRun]: ...
    def save(self, run: ScanRun) -> ScanRun: ...
    def list_recent(self, retention_days: int) -> List[ScanRun]: ...
    def acquire_job(
        self,
        slot_key: str,
        scheduled_for: datetime,
        started_at: datetime,
        lease_expires_at: datetime,
        maximum_attempts: int,
    ) -> bool: ...
    def finish_job(
        self,
        slot_key: str,
        status: str,
        finished_at: datetime,
        scan_run_id: Optional[str] = None,
        error: Optional[str] = None,
    ) -> None: ...
    def list_jobs(self, limit: int) -> List[ScheduledScanJob]: ...
